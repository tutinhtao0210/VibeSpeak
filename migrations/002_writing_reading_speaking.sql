CREATE TABLE passages(
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  key TEXT NOT NULL UNIQUE, topic TEXT NOT NULL,
  level INTEGER NOT NULL DEFAULT 2, vi TEXT NOT NULL, en TEXT NOT NULL,
  words INTEGER NOT NULL, quiz TEXT NOT NULL DEFAULT '[]');
CREATE TABLE writings(
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  passage_id INTEGER REFERENCES passages(id) ON DELETE SET NULL,
  text TEXT NOT NULL, word_count INTEGER NOT NULL,
  score REAL NOT NULL DEFAULT 0, feedback TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE speeches(
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  kind TEXT NOT NULL DEFAULT 'intro',
  transcript TEXT NOT NULL, word_count INTEGER NOT NULL,
  duration INTEGER NOT NULL DEFAULT 0,
  score REAL NOT NULL DEFAULT 0, feedback TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
