CREATE TABLE IF NOT EXISTS users(
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  name TEXT NOT NULL,
  accent TEXT NOT NULL DEFAULT 'en-US' CHECK(accent IN('en-US','en-GB')),
  base_level INTEGER NOT NULL DEFAULT 1 CHECK(base_level BETWEEN 1 AND 4),
  place TEXT NOT NULL DEFAULT '',
  daily_done TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS words(
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  word TEXT NOT NULL UNIQUE,
  meaning TEXT NOT NULL,
  example TEXT NOT NULL,
  level INTEGER NOT NULL CHECK(level BETWEEN 1 AND 4)
);

CREATE TABLE IF NOT EXISTS questions(
  id TEXT PRIMARY KEY,
  level INTEGER NOT NULL CHECK(level BETWEEN 1 AND 4),
  skill TEXT NOT NULL CHECK(skill IN('listen','speak','read','write','grammar')),
  topic TEXT NOT NULL,
  prompt TEXT NOT NULL,
  target TEXT NOT NULL DEFAULT '',
  audio TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS options(
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  question_id TEXT NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
  text TEXT NOT NULL,
  is_correct INTEGER NOT NULL DEFAULT 0,
  sort_order INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_options_q ON options(question_id);

CREATE TABLE IF NOT EXISTS scenarios(
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  icon TEXT NOT NULL,
  title TEXT NOT NULL,
  prompt TEXT NOT NULL,
  tip TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS scenario_options(
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  scenario_id INTEGER NOT NULL REFERENCES scenarios(id) ON DELETE CASCADE,
  text TEXT NOT NULL,
  is_best INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS attempts(
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  tab TEXT NOT NULL,
  title TEXT NOT NULL,
  score REAL NOT NULL DEFAULT 0,
  total INTEGER NOT NULL DEFAULT 0,
  note TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS answers(
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  attempt_id INTEGER REFERENCES attempts(id) ON DELETE CASCADE,
  question_id TEXT REFERENCES questions(id) ON DELETE SET NULL,
  skill TEXT NOT NULL CHECK(skill IN('listen','speak','read','write','grammar')),
  tab TEXT NOT NULL,
  score REAL NOT NULL CHECK(score BETWEEN 0 AND 1),
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_answers_u ON answers(user_id, skill, id);

CREATE TABLE IF NOT EXISTS study_days(
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  day TEXT NOT NULL,
  xp INTEGER NOT NULL DEFAULT 0,
  UNIQUE(user_id, day)
);

CREATE TABLE IF NOT EXISTS seen(
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  tab TEXT NOT NULL,
  item TEXT NOT NULL,
  PRIMARY KEY(user_id, tab, item)
);

CREATE TABLE IF NOT EXISTS wrong(
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  question_id TEXT NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
  count INTEGER NOT NULL DEFAULT 1,
  PRIMARY KEY(user_id, question_id)
);

CREATE TABLE IF NOT EXISTS notes(
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  type TEXT NOT NULL CHECK(type IN('Từ vựng','Mẫu câu','Câu hay','Lỗi')),
  content TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
